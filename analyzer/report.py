"""One-page markdown change report. Pure Python.

States what was and was NOT verified for the rewrite as a whole, per change, and never includes
a performance number (none are measured by the hosted app).
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional

from analyzer.status import MATCHED, PERF, STATUSES, StatusInfo


@dataclass(frozen=True)
class ChangeItem:
    title: str
    explanation: str
    risk: Optional[str] = None


def _fence(code: str) -> str:
    longest = max((len(m) for m in re.findall(r"`+", code)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}sql\n{code.strip()}\n{ticks}"


def _one_line(s: str) -> str:
    return " ".join(s.split())


def build_change_report(original_sql: str, rewritten_sql: Optional[str], dialect_label: str,
                        status: Optional[StatusInfo], changes=(), findings=(), notes=(),
                        title: str = "SQL change report") -> str:
    lines = [f"# {title}", "", f"Dialect: **{dialect_label}**", ""]
    if findings:
        lines += ["## Rule findings (deterministic analyzer)", ""]
        for f in findings:
            where = f" (line {f.line})" if f.line else ""
            lines.append(f"- **{f.rule_id}** [{f.severity}]{where}: {_one_line(f.message)}")
        lines.append("")
    lines += ["## Original", "", _fence(original_sql), ""]
    if rewritten_sql:
        lines += ["## Proposed rewrite", "", _fence(rewritten_sql), ""]
        st = status or StatusInfo(STATUSES[0])
        lines += [f"**Validation status: {st.status}**", ""]
        for fl in st.flags:
            lines.append(f"- Flag: {fl}")
        lines.append("")
    if changes:
        lines += ["## Changes", ""]
        for i, c in enumerate(changes, 1):
            lines.append(f"{i}. **{_one_line(c.title)}**: {_one_line(c.explanation)}")
            if c.risk:
                lines.append(f"   - Risk: {_one_line(c.risk)}")
        lines.append("")
    if notes:
        lines += ["## Notes", ""] + [f"- {_one_line(n)}" for n in notes] + [""]

    lines += ["## What was NOT verified", ""]
    rank = STATUSES.index(status.status) if (rewritten_sql and status) else 0
    if not rewritten_sql:
        lines.append("- No rewrite was proposed.")
    else:
        if rank < STATUSES.index(MATCHED):
            lines.append("- Results were NOT compared with the original on any data.")
        else:
            lines.append("- Results matched on GENERATED test data only. This is evidence, not proof "
                         "of equivalence; production data, NULL patterns, collations and edge cases may differ.")
        if rank < STATUSES.index(PERF):
            lines.append("- Performance was NOT measured. No speed-up is claimed.")
        lines.append("- The rewrite was not run against the real database.")
    lines += ["", "_Generated by QueryTune AI. Review before use._", ""]
    return "\n".join(lines)
